const i18n = { lang: "en", pref: "auto", system: "en" };

function t(s, vars) {
  let r = (i18n.lang === "ru" && RU[s]) || s;
  if (vars) r = r.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m));
  return r;
}

function tb(s) {
  if (i18n.lang !== "ru" || !s) return s;
  if (RU[s]) return RU[s];
  for (const [re, fn] of RU_PATTERNS) {
    const m = s.match(re);
    if (m) return fn(...m);
  }
  return s;
}

const staticText = [];

function collectStatic() {
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
    acceptNode: (n) => n.parentElement.closest("script, style, svg, #log") || !n.nodeValue.trim() ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT,
  });
  for (let n = walker.nextNode(); n; n = walker.nextNode()) staticText.push({ node: n, raw: n.nodeValue, key: n.nodeValue.trim() });
  for (const el of document.querySelectorAll("[title], [aria-label]")) {
    for (const attr of ["title", "aria-label"]) {
      const v = el.getAttribute(attr);
      if (v) staticText.push({ el, attr, key: v });
    }
  }
}

function applyStatic() {
  for (const s of staticText) {
    if (s.node) s.node.nodeValue = s.raw.replace(s.key, t(s.key));
    else s.el.setAttribute(s.attr, t(s.key));
  }
  document.documentElement.lang = i18n.lang;
}

function resolveLang() {
  i18n.lang = i18n.pref === "ru" || i18n.pref === "en" ? i18n.pref : i18n.system === "ru" ? "ru" : "en";
}
