const i18n = { lang: "en", pref: "auto", system: "en" };

function t(s, vars) {
  let r = (i18n.lang === "ru" && RU[s]) || s;
  if (vars) r = r.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m));
  return r;
}

function tb(s) {
  if (i18n.lang !== "ru" || !s) return s;
  if (RU[s]) return RU[s];
  for (const [re, fn] of RU_PATTERNS) {
    const m = s.match(re);
    if (m) return fn(...m);
  }
  return s;
}

